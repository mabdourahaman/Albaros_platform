# ---------------------------
# QUIZ EVALUATION
# ---------------------------
def evaluate_quiz(user_id, quiz_id, answers):
    questions = Question.query.filter_by(quiz_id=quiz_id).all()
    if not questions:
        return {"score": 0, "gaps": []}
    
    total = len(questions)
    correct = 0
    concept_correct = {}
    concept_total = {}
    
    for q in questions:
        user_answer = answers.get(str(q.id))
        if user_answer and int(user_answer) == q.correct_option:
            correct += 1
            concept_correct[q.concept] = concept_correct.get(q.concept, 0) + 1
        concept_total[q.concept] = concept_total.get(q.concept, 0) + 1
    
    score = (correct / total) * 100
    
    xp_earned = correct * 5
    gems_earned = correct // 2
    from models import User
    user = User.query.get(user_id)
    user.total_xp = (user.total_xp or 0) + xp_earned
    user.gems = (user.gems or 0) + gems_earned
    
    # Mise à jour des gaps basée sur le taux de réussite par concept
    for concept, tot in concept_total.items():
        if concept is None:
            continue
        corr = concept_correct.get(concept, 0)
        success_rate = (corr / tot) * 100
        gap = Gap.query.filter_by(user_id=user_id, concept=concept).first()
        if not gap:
            gap = Gap(user_id=user_id, concept=concept, mastery_level=50.0)  # niveau initial à 50
            db.session.add(gap)
        if success_rate >= 70:
            # Réussite : +5 (max 100)
            gap.mastery_level = min(gap.mastery_level + 5, 100)
        elif success_rate < 50:
            # Échec : -10 (min 0)
            gap.mastery_level = max(gap.mastery_level - 10, 0)
        # Entre 50% et 70% -> pas de changement
        gap.last_updated = date.today()
    
    db.session.commit()
    
    # Détection des gaps pour l'affichage (ceux avec mastery_level < 50 ? ou comme avant ?)
    # On garde l'ancienne liste pour la réponse (concepts avec succès < 50% dans ce quiz)
    gaps_detected = []
    for concept, tot in concept_total.items():
        if concept is None:
            continue
        corr = concept_correct.get(concept, 0)
        if (corr / tot) < 0.5:
            gaps_detected.append(concept)
    
    result = QuizResult(
        user_id=user_id,
        quiz_id=quiz_id,
        score=score,
        answers_json=json.dumps(answers),
        gaps_json=json.dumps(gaps_detected)
    )
    db.session.add(result)
    db.session.commit()
    
    update_quest_progress(user_id, 'exercises', 1)
    update_quest_progress(user_id, 'xp', xp_earned)
    
    return {
        "score": score,
        "gaps": gaps_detected,
        "xp_earned": xp_earned,
        "gems_earned": gems_earned
    }

