def get_or_create_gaps_course():
    course = Course.query.filter_by(title="Gaps Exercises").first()
    if not course:
        course = Course(
            title="Gaps Exercises",
            description="Exercises generated by AI to reinforce your weak points",
            difficulty="mixed",
            tags="generated,ai"
        )
        db.session.add(course)
        db.session.commit()
    return course

def get_week_start():
    """Retourne le lundi de la semaine en cours."""
    today = date.today()
    return today - timedelta(days=today.weekday())

# ---------------------------
# QUEST PROGRESS HELPERS
# ---------------------------
def update_quest_progress(user_id, objective_type, increment=1):
    week_start = get_week_start()
    progresses = UserQuestProgress.query.join(Quest).filter(
        UserQuestProgress.user_id == user_id,
        UserQuestProgress.week_start_date == week_start,
        UserQuestProgress.completed == False,
        Quest.objective_type == objective_type
    ).all()
    for prog in progresses:
        prog.progress += increment
        if prog.progress >= prog.quest.objective_target:
            prog.completed = True
        db.session.add(prog)
    db.session.commit()

