def get_gaps(user_id):
    gaps = Gap.query.filter_by(user_id=user_id).all()
    return [{"concept": g.concept, "level": g.mastery_level} for g in gaps]

def map_difficulty_to_xp(difficulty):
    mapping = {'easy': 20, 'medium': 30, 'hard': 40}
    return mapping.get(difficulty.lower(), 20)

def generate_personalized_exercises(user_id, limit=5, revision=False):
    if revision:
        completed_ids = [ue.exercise_id for ue in UserExercise.query.filter_by(user_id=user_id, completed=True).all()]
        exercises = Exercise.query.filter(Exercise.id.in_(completed_ids)).limit(limit).all()
        return [{
            "id": e.id,
            "question": e.question_text,
            "difficulty": e.difficulty,
            "xp_reward": e.xp_reward if hasattr(e, 'xp_reward') else map_difficulty_to_xp(e.difficulty)
        } for e in exercises]

    gaps = Gap.query.filter_by(user_id=user_id).all()
    if not gaps:
        exercises = Exercise.query.filter_by(difficulty='easy').limit(limit).all()
        return [{
            "id": e.id,
            "question": e.question_text,
            "difficulty": e.difficulty,
            "xp_reward": e.xp_reward if hasattr(e, 'xp_reward') else map_difficulty_to_xp(e.difficulty)
        } for e in exercises]

    gaps_course = get_or_create_gaps_course()
    new_exercises = []

    for gap in gaps[:limit]:
        existing = Exercise.query.filter(Exercise.tags.like(f'%{gap.concept}%')).first()
        if existing:
            new_exercises.append(existing)
            continue
        
        # Générer un nouvel exercice via Ollama
        gen_data = generate_exercise_for_gap(gap.concept, "medium")
        if gen_data:
            exercise = Exercise(
                course_id=gaps_course.id,
                question_text=gen_data['question'],
                correct_answer=gen_data['correct_answer'],
                explanation=gen_data.get('explanation', ''),
                difficulty=gen_data.get('difficulty', 'medium'),
                tags=gap.concept,
                xp_reward=map_difficulty_to_xp(gen_data.get('difficulty', 'medium'))
            )
            db.session.add(exercise)
            db.session.commit()
            new_exercises.append(exercise)
        else:
            fallback = Exercise.query.order_by(func.random()).first()
            if fallback:
                new_exercises.append(fallback)

        if len(new_exercises) >= limit:
            break

    if len(new_exercises) < limit:
        existing_ids = [e.id for e in new_exercises]
        remaining = limit - len(new_exercises)
        random_ex = Exercise.query.filter(Exercise.id.notin_(existing_ids)).limit(remaining).all()
        new_exercises.extend(random_ex)

    return [{
        "id": e.id,
        "question": e.question_text,
        "difficulty": e.difficulty,
        "xp_reward": e.xp_reward if hasattr(e, 'xp_reward') else map_difficulty_to_xp(e.difficulty)
    } for e in new_exercises]